// Generates src/i18n/declaration.ts (the I18nKey enum) from src/i18n/translation.json.
// The translations themselves are bundled into the app (no runtime fetch), so the counter PC
// works offline. Run automatically before lint, build and test.
const fs = require("fs");
const path = require("path");

const translations = JSON.parse(
  fs.readFileSync(path.join(__dirname, "../src/i18n/translation.json"), "utf8"),
);
const keys = Object.keys(translations);
const out = path.join(__dirname, "../src/i18n/declaration.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// This file is generated by scripts/make-i18n-translations.cjs. Do not edit it.
export enum I18nKey {
${keys.map((key) => `  ${key} = "${key}",`).join("\n")}
}
`,
);
console.log(`wrote ${keys.length} keys to src/i18n/declaration.ts`);
