// Generates src/api/schema.d.ts from the backend's OpenAPI document. The backend is imported
// (not started), so no server and no keys are needed. The output is committed, so the web build
// never needs the backend.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const code = "import json;from app.main import app;print(json.dumps(app.openapi()))";
const raw = execFileSync(
  "uv",
  ["--directory", join(here, "../../backend"), "run", "python", "-c", code],
  { encoding: "utf8", env: { ...process.env, LLM_PROVIDER: "offline", AUDIT_SINK: "none" } },
);
const document = JSON.parse(raw.slice(raw.indexOf("{")));
const ast = await openapiTS(document);
const header = "// Generated by `npm run gen:api` from the backend OpenAPI document. Do not edit.\n";
writeFileSync(join(here, "../src/api/schema.d.ts"), header + astToString(ast));
console.log("wrote src/api/schema.d.ts");
